CREATE SEQUENCE SEQ_CATALOG_RESOURCE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE CATALOG_RESOURCES (
    ID            NUMBER(19)      NOT NULL,
    NAME          VARCHAR2(150)   NOT NULL,
    RESOURCE_TYPE VARCHAR2(20)    NOT NULL,
    DESCRIPTION   VARCHAR2(500),
    LOCATION      VARCHAR2(100),
    STOCK_CUPO    NUMBER(10)      NOT NULL,
    CREATED_AT    TIMESTAMP       NOT NULL,
    UPDATED_AT    TIMESTAMP       NOT NULL,
    CONSTRAINT PK_CATALOG_RESOURCES PRIMARY KEY (ID),
    CONSTRAINT CHK_RESOURCE_TYPE CHECK (RESOURCE_TYPE IN ('LABORATORIO', 'EQUIPO', 'INSUMO')),
    CONSTRAINT CHK_STOCK_CUPO_NON_NEG CHECK (STOCK_CUPO >= 0)
);

CREATE INDEX IDX_CATALOG_RESOURCE_TYPE ON CATALOG_RESOURCES (RESOURCE_TYPE);
